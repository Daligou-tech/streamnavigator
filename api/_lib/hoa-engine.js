// request. On a single reserve study that took 654 seconds against Vercel's
// 800 second ceiling, and at the ceiling the report does not degrade — it
// fails. A full package (reserve study, budget, financials, minutes) would
// not have finished.
//
// Splitting evidence from synthesis is not enough on its own, because the
// evidence pass is the expensive half. So the evidence pass is split per
// document: each document is read in its own invocation with its own full
// budget, and the cross-document work happens afterwards in a synthesis step
// that needs no documents attached and is therefore fast. Adding documents now
// costs more invocations rather than more seconds inside one, so the wall is
// gone rather than moved.
//
// The state that has to survive between invocations is the per-document
// narrative and its harvested citations, which is what navigator_submissions
// .job_state holds. A failure keeps job_state, so a transient API error costs
// one document's work rather than the whole run.
//
// api/hoa-job.js drives this a stage at a time, once a minute.

const JOB_STAGE_EVIDENCE = 'evidence';
const JOB_STAGE_SYNTHESIS = 'synthesis';

// A stage that has not reported back in this long is treated as abandoned —
// the platform killed it outside this code's own try/catch, so nothing
// updated the row. Must stay above the function's 800s maxDuration or a stage
// still legitimately running gets started a second time alongside itself.
const STAGE_STALL_MS = 20 * 60 * 1000;

// Bounds retries on a submission that fails repeatedly, so a document the
// model cannot read does not loop forever at Opus prices.
const MAX_JOB_ATTEMPTS = 3;

// One stage per document plus the synthesis, with slack. The intake caps a
// submission at 12 files (api/_lib/upload-limits.js), so this only ever trips
// on a bug that fails to advance the stage.
const MAX_STAGES = 16;

function anthropicClient() {
  const ANTHROPIC_API_KEY = process.env.ANTHROPIC_API_KEY;
  if (!ANTHROPIC_API_KEY) throw new Error('Missing ANTHROPIC_API_KEY env var');
  return new Anthropic({ apiKey: ANTHROPIC_API_KEY });
}

async function fetchSubmission(admin, submissionId) {
  const { data, error } = await admin
    .from('navigator_submissions')
    .select('*')
    .eq('id', submissionId)
    .single();
  if (error || !data) throw new Error('Submission not found');
  return data;
}

async function saveJob(admin, submissionId, job, extra) {
  await admin
    .from('navigator_submissions')
    .update(Object.assign({ job_state: job, updated_at: new Date().toISOString() }, extra || {}))
    .eq('id', submissionId);
}

// hoa.html submits exactly one optional free-text field (#intake-description,
// sent as form_data.description). It is where a buyer typically supplies unit
// count, build year, and what the seller has claimed — all of which matter to
// per-unit exposure and are worth weighing against the documents rather than
// taking at face value.
function buildContextLines(submission, docTitles) {
  const formData = submission.form_data || {};
  return [
    formData.description
      ? `What the buyer told us (their words, not verified — check it against the documents): ${formData.description}`
      : 'The buyer did not add any description of the property.',
    `Documents in this package (${docTitles.length}): ${docTitles.join(', ')}`,
  ].join('\n');
}

// Sets up job_state from the submission's files. Does no model work.
async function startJob(admin, submission) {
  const filePaths = submission.file_paths || [];
  if (!filePaths.length) {
    throw new Error('HOA Navigator requires at least one uploaded document, but none were found on this submission.');
  }

  const docs = filePaths.map((path) => ({ path, title: displayName(path) }));
  const job = {
    stage: JOB_STAGE_EVIDENCE,
    docIndex: 0,
    docs,
    parts: [],
    context: buildContextLines(submission, docs.map((d) => d.title)),
    started_at: new Date().toISOString(),
  };

  await saveJob(admin, submission.id, job, { status: 'processing', error: null });
  return job;
}

// Reads one document: Supabase -> Files API -> evidence pass -> delete. Only
// this document is in play, so a package of any size never puts more than one
// file through a single invocation.
async function analyseOneDocument(client, admin, { path, title, context, index, total }) {
  const { data: fileBlob, error: downloadError } = await admin.storage
    .from('navigator-uploads')
    .download(path);
  if (downloadError || !fileBlob) {
    throw new Error(`Could not read ${title} from storage.`);
  }

  const mediaType = guessMediaType(path);
  const buffer = Buffer.from(await fileBlob.arrayBuffer());

  const uploaded = await client.files.upload({
    file: await toFile(buffer, basename(path), { type: mediaType }),
  });

  try {
    let block;
    if (mediaType === 'application/pdf') {
      block = {
        type: 'document',
        source: { type: 'file', file_id: uploaded.id },
        title,
        citations: { enabled: true },
      };
    } else {
      // Images cannot carry citations. Still worth reading — an assessment
      // notice photographed on a phone is a real case — but findings resting
      // on one will have no evidence to reference, which the model is told
      // to flag.
      block = { type: 'image', source: { type: 'file', file_id: uploaded.id } };
    }

    const header = [
      context,
      '',
      `THIS DOCUMENT: "${title}" (document ${index + 1} of ${total}).`,
      mediaType === 'application/pdf'
        ? ''
        : 'This upload is an image, not a PDF, so it cannot produce page citations — say so if anything here matters.',
    ].filter(Boolean).join('\n');

    const { response } = await runToCompletion(client, {
      system: EVIDENCE_SYSTEM,
      maxTokens: MAX_TOKENS_EVIDENCE,
      tools: [{ type: 'code_execution_20260521', name: 'code_execution' }],
      messages: [{ role: 'user', content: [block, { type: 'text', text: header }] }],
    });

    const narrative = textOf(response.content);
    if (!narrative) throw new Error(`Reading ${title} produced no analysis text.`);

    return { title, narrative, evidence: harvestCitations(response.content) };
  } finally {
    // The buyer's documents have no reason to sit in the org's file store
    // once this pass has read them.
    await client.files.delete(uploaded.id).catch((e) => {
      console.warn(`[hoa-engine] could not delete file ${uploaded.id}: ${e.message}`);
    });
  }
}

// Merges the per-document citations into one table. Indices in that table are
// what findings reference and what attachCitations resolves against, so the
// merge has to happen exactly once, here.
function mergeEvidence(parts) {
  const seen = new Map();
  for (const part of parts) {
    for (const c of part.evidence || []) {
      const key = [c.document_title, c.page_start, c.page_end, c.cited_text].join('|');
      if (!seen.has(key)) seen.set(key, c);
    }
  }
  return Array.from(seen.values());
}

async function runSynthesis(client, job) {
  const evidence = mergeEvidence(job.parts);

  const analyses = job.parts
    .map((p, i) => `--- DOCUMENT ${i + 1}: ${p.title} ---\n\n${p.narrative}`)
    .join('\n\n');

  const { toolInput } = await runToCompletion(client, {
    system: REPORT_SYSTEM,
    maxTokens: MAX_TOKENS_EVIDENCE,
    tools: [
      { type: 'code_execution_20260521', name: 'code_execution' },
      REPORT_TOOL,
    ],
    expectToolName: REPORT_TOOL_NAME,
    messages: [{
      role: 'user',
      content: `${job.context}\n\nPER-DOCUMENT ANALYSES\n\n${analyses}\n\n---\n\n${formatEvidenceTable(evidence)}`,
    }],
  });

  const { report, droppedCitationRefs, unverifiedPinpoints } = attachCitations(toolInput, evidence);

  report.evidence = evidence;
  report.documents_analysed = job.parts.map((p) => p.title);
  report.generated_at = new Date().toISOString();
  report.disclaimer = 'This is an analysis of the documents provided, not legal, financial, or investment advice, and not a substitute for review by an attorney, accountant, or licensed inspector. Dollar figures are estimates unless quoted directly from a document. Verify anything you intend to rely on before waiving a contingency.';

  return { report, droppedCitationRefs, unverifiedPinpoints };
}

// Advances one submission by exactly one stage, then returns. This is the unit
// of work a single Vercel invocation performs.
async function advanceHoaJob(submissionId) {
  const admin = getSupabaseAdmin();
  const submission = await fetchSubmission(admin, submissionId);

  try {
    let job = submission.job_state;
    if (!job) job = await startJob(admin, submission);

    // Claim the stage before doing any work. job_running_since is what tells
    // a worker tick landing mid-stage to leave this alone; updated_at cannot,
    // because a submission waiting for its next stage and one currently
    // running a stage both sit at 'processing' with a recent updated_at. It
    // is cleared the moment the stage returns, so the next tick picks the
    // job straight back up instead of idling for the stall window.
    await saveJob(admin, submissionId, job, {
      status: 'processing',
      job_running_since: new Date().toISOString(),
    });

    const client = anthropicClient();

    if (job.stage === JOB_STAGE_EVIDENCE) {
      const doc = job.docs[job.docIndex];
      const part = await analyseOneDocument(client, admin, {
        path: doc.path,
        title: doc.title,
        context: job.context,
        index: job.docIndex,
        total: job.docs.length,
      });

      job.parts.push(part);
      job.docIndex += 1;
      if (job.docIndex >= job.docs.length) job.stage = JOB_STAGE_SYNTHESIS;

      // Released, so the next tick continues immediately.
      await saveJob(admin, submissionId, job, { job_running_since: null });
      return {
        done: false,
        stage: job.stage,
        documentsRead: job.docIndex,
        documentsTotal: job.docs.length,
      };
    }

    const { report, droppedCitationRefs, unverifiedPinpoints } = await runSynthesis(client, job);

    await admin.from('navigator_reports').insert({
      submission_id: submissionId,
      product: 'hoa',
      report_json: report,
      model: HOA_MODEL,
    });

    await admin
      .from('navigator_submissions')
      .update({
        status: 'complete',
        job_state: null,
        job_running_since: null,
        error: null,
        updated_at: new Date().toISOString(),
      })
      .eq('id', submissionId);

    if (droppedCitationRefs > 0) {
      console.warn(`[hoa-engine] submission ${submissionId}: dropped ${droppedCitationRefs} invalid citation reference(s)`);
    }
    if (unverifiedPinpoints > 0) {
      console.warn(`[hoa-engine] submission ${submissionId}: discarded ${unverifiedPinpoints} pinpoint quote(s) that did not appear in the cited evidence`);
    }

    return { done: true, stage: 'complete', report };
  } catch (err) {
    // job_state is deliberately left in place. A transient API failure should
    // cost the one document that was in flight, not the documents already
    // read — the next attempt resumes at the same docIndex.
    await admin
      .from('navigator_submissions')
      .update({
        status: 'failed',
        error: String(err.message || err).slice(0, 500),
        generation_attempts: (submission.generation_attempts || 0) + 1,
        // Released so a retry is not mistaken for a stage still in flight.
        job_running_since: null,
        updated_at: new Date().toISOString(),
      })
      .eq('id', submissionId);
    throw err;
  }
}

// Runs every remaining stage in one process. Used by the admin endpoint and
// the tests; NOT by the customer path, which advances a stage per invocation
// precisely so it never has to fit inside one function's time budget.
async function generateHoaReport(submissionId) {
  for (let i = 0; i < MAX_STAGES; i++) {
    const result = await advanceHoaJob(submissionId);
    if (result.done) return result.report;
  }
  throw new Error(`HOA job did not finish within ${MAX_STAGES} stages`);
}

