function guessMediaType(filename) {
  const ext = String(filename).toLowerCase().split('.').pop();
  if (ext === 'pdf') return 'application/pdf';
  if (ext === 'png') return 'image/png';
  if (ext === 'webp') return 'image/webp';
  if (ext === 'gif') return 'image/gif';
  if (ext === 'heic' || ext === 'heif') return 'image/heic';
  return 'image/jpeg';
}

function basename(path) {
  const parts = String(path).split('/');
  return parts[parts.length - 1] || String(path);
}

// The document title given to the API ends up in every citation the customer
// reads, so it cannot be the raw storage key. Uploads are stored as
// "<epoch-ms>-<original name>", which rendered in the first production run as
// "1788102669194-hoa_governing_docs_sample.pdf" underneath each quoted
// passage. Strip the upload timestamp and turn separators back into spaces.
function displayName(path) {
  return basename(path)
    .replace(/^\d{10,}-/, '')
    .replace(/[_]+/g, ' ')
    .trim() || basename(path);
}

// Pull the API-generated citations off the response's text blocks. These
// are produced by the citation system from the source document — the page
// numbers and cited_text are not model-authored, which is the entire point
// of running the evidence pass separately. Deduplicated, because the model
// will often cite the same passage supporting several claims.
function harvestCitations(content) {
  const seen = new Map();
  for (const block of content || []) {
    if (block.type !== 'text' || !Array.isArray(block.citations)) continue;
    for (const c of block.citations) {
      const pageStart = c.start_page_number != null ? c.start_page_number : null;
      const pageEnd = c.end_page_number != null ? c.end_page_number : null;
      const key = [c.document_index, c.document_title, pageStart, pageEnd, c.cited_text].join('|');
      if (seen.has(key)) continue;
      seen.set(key, {
        document_title: c.document_title || null,
        document_index: c.document_index != null ? c.document_index : null,
        page_start: pageStart,
        page_end: pageEnd,
        cited_text: (c.cited_text || '').trim(),
      });
    }
  }
  return Array.from(seen.values());
}

function formatEvidenceTable(evidence) {
  if (!evidence.length) {
    return 'EVIDENCE TABLE\n\n(No citations were captured. Do not cite any evidence ids — leave every evidence_ids array empty, and say plainly in missing_or_uncertain that findings could not be tied to specific pages.)';
  }
  const rows = evidence.map((e, i) => {
    const pages = e.page_start
      ? (e.page_end && e.page_end !== e.page_start ? `pp. ${e.page_start}-${e.page_end}` : `p. ${e.page_start}`)
      : 'page unknown';
    return `[${i}] ${e.document_title || 'Untitled document'} (${pages})\n    "${e.cited_text.slice(0, 600)}"`;
  });
  return `EVIDENCE TABLE\n\n${rows.join('\n\n')}`;
}

function textOf(content) {
  return (content || [])
    .filter((b) => b.type === 'text')
    .map((b) => b.text)
    .join('\n')
    .trim();
}

// Replace every evidence_ids array in the report with the actual harvested
// citations, dropping any index the model made up. This is what makes the
// shipped page numbers trustworthy: they are copied out of the harvested
// table, never read from what the model wrote.
// Whitespace-insensitive, case-insensitive comparison. Citation text from a
// PDF arrives with the source's own line breaks and column padding
// ("$22,365.62" can sit inside a run of spaces in a ledger row), so an exact
// string compare would reject quotes that are genuinely present.
function normalizeForMatch(value) {
  return String(value || '').replace(/\s+/g, ' ').trim().toLowerCase();
}

function attachCitations(report, evidence) {
  let dropped = 0;
  let unverifiedPinpoints = 0;

  // A pinpoint is the model saying "this exact line is what I mean". It is
  // model-written, so it is only allowed to reach the customer if it appears
  // verbatim inside evidence the API itself returned. Anything that fails
  // that check is discarded rather than shown, which keeps the same guarantee
  // the page numbers have: nothing quoted was authored by the model.
  function verifyPinpoint(node) {
    if (typeof node.pinpoint !== 'string') return;
    const needle = normalizeForMatch(node.pinpoint);
    if (!needle) { node.pinpoint = ''; return; }
    const haystack = (node.citations || []).map((c) => normalizeForMatch(c.cited_text)).join('   ');
    if (!haystack.includes(needle)) {
      node.pinpoint = '';
      unverifiedPinpoints++;
    }
  }

  function resolve(ids) {
    const out = [];
    for (const id of Array.isArray(ids) ? ids : []) {
      const item = evidence[id];
      if (!item) { dropped++; continue; }
      out.push(item);
    }
    return out;
  }

  function walk(node) {
    if (Array.isArray(node)) { node.forEach(walk); return; }
    if (!node || typeof node !== 'object') return;
    if (Object.prototype.hasOwnProperty.call(node, 'evidence_ids')) {
      node.citations = resolve(node.evidence_ids);
      delete node.evidence_ids;
      verifyPinpoint(node);
    }
    Object.values(node).forEach(walk);
  }

  walk(report);
  return { report, droppedCitationRefs: dropped, unverifiedPinpoints };
}

// Runs a request to completion, continuing through pause_turn (which the
// server-side code execution tool can produce on a long turn) and nudging
// once if the model ends its turn without calling the report tool.
// `effort` defaults to the paid report's level. The free check
// (api/hoa-scorecard.js) passes a lower one: it runs a single pass whose
// figures are arithmetic the code execution tool does exactly, so the depth
// that earns its cost on the full analysis is not needed there.
async function runToCompletion(client, { system, messages, tools, maxTokens, expectToolName, effort }) {
  const working = messages.slice();

  for (let turn = 0; turn < MAX_TURNS; turn++) {
    const request = {
      model: HOA_MODEL,
      max_tokens: maxTokens,
      system,
      thinking: { type: 'adaptive' },
      output_config: { effort: effort || EFFORT },
      messages: working,
    };
    if (tools) {
      request.tools = tools;
      // Deliberately not a forced tool_choice. Forcing the tool conflicts
      // with thinking (see purchase-engine.js:390), and 'auto' plus an
      // explicit instruction in the system prompt achieves the same thing
      // without that constraint.
      request.tool_choice = { type: 'auto' };
    }

    const response = await client.messages.stream(request).finalMessage();

    if (response.stop_reason === 'refusal') {
      const detail = response.stop_details ? ` (${response.stop_details.category})` : '';
      throw new Error(`Model declined to complete the analysis${detail}`);
    }

    if (expectToolName) {
      const toolUse = response.content.find(
        (b) => b.type === 'tool_use' && b.name === expectToolName,
      );
      if (toolUse) return { toolInput: toolUse.input, response };
    }

    if (response.stop_reason === 'pause_turn') {
      working.push({ role: 'assistant', content: response.content });
      continue;
    }

    if (!expectToolName) return { response };

    // Ended its turn without producing the report. Ask once, explicitly.
    working.push({ role: 'assistant', content: response.content });
    working.push({
      role: 'user',
      content: `Call the ${expectToolName} tool now with the structured report.`,
    });
  }

  throw new Error(`Analysis did not complete within ${MAX_TURNS} turns`);
}

