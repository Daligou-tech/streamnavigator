// Dedicated analysis engine for HOA Navigator.
//
// HOA was previously handled as one of eleven `task` strings inside the
// shared api/_lib/navigator-engine.js. That generic path could not honour
// what hoa.html actually sells, in three specific ways:
//
//   1. The page promises "Every finding cites the page it came from" and
//      "top 5 concerns, each backed by a page-level citation". The generic
//      engine never enabled document citations and its shared schema had
//      no citation field, so any page number in a shipped report was the
//      model writing a number into a prose field — unverified.
//   2. The page sells an "HOA Risk Score — Low, Moderate, High, or
//      Critical". In the generic schema that was free text in
//      `headline_tag`, with no typed value anywhere.
//   3. Reserve analysis is arithmetic (percent funded, contribution
//      shortfall, per-unit exposure, projecting a reserve balance against
//      planned capital spend). The generic engine asked the model to do
//      that in its head. That is the same failure mode behind the
//      2026-08-31 purchase-engine incident, where the model reproducibly
//      tried to "show its work" by emitting simulated tool-call syntax
//      into a prose field. Patches 0004-0007 treated that with sanitizing,
//      prompt scolding and a thinking scratchpad; none of them gave it an
//      actual calculator.
//
// This engine addresses all three directly:
//
//   * Staged passes. An EVIDENCE pass reads ONE document with citations
//     enabled and code execution available, and writes a prose analysis.
//     The API attaches real citations (document index, page range, and the
//     exact quoted text) to the text blocks it returns — those are
//     generated by the citation system from the actual document, not
//     recalled by the model. We harvest them into a numbered evidence
//     table. Once every document has been read, a SYNTHESIS pass does the
//     cross-document work (a reserve study states a fully funded balance,
//     the budget shows what is actually contributed, the minutes say
//     whether the board has discussed it) and emits the report schema,
//     where every finding references evidence by index. We validate each
//     index server-side and splice in the harvested citation. A page number
//     in a shipped report therefore comes from the API, never from the
//     model's own writing.
//
//     Each stage is a separate invocation — see the staged-generation
//     section at the bottom of this file for why, and api/hoa-job.js for
//     what drives it.
//   * A typed HOA schema with `strict: true`, so risk_score is a real enum
//     and the API guarantees the tool input validates. `strict` is also
//     why this file has no equivalent of navigator-engine's
//     TAG_LEAK_PATTERN regex and its retry loop — schema-invalid output is
//     rejected server-side rather than detected here after the fact.
//   * The code_execution tool, so reserve maths runs as real Python.
//
// Documents go through the Files API rather than being base64-inlined into
// the request. Inlining was at the edge of the 32MB request ceiling: the
// intake allows 4 files x 6MB, and 24MB of PDF base64-encodes to roughly
// 32.8MB, so a customer who uploaded the maximum the form permits could
// produce a request the API would reject. Uploaded files are deleted in a
// finally block — these are a named person's financial documents and there
// is no reason to leave them in the org's file store after the run.
//
// Requires the same ANTHROPIC_API_KEY the other engines use.

